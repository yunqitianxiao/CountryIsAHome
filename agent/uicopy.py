"""把「写给智能体 / 写给维护者」的字符串，在**出 HTTP 边界那一刻**换成「写给人」的。

★背景：这一站的后端字符串有两个读者。一个是浏览器里的小白，一个是进程内的大模型
  （`/api/chat` 那条路拿 `tools.call` 的原文，里面那些「说的时候必须带上限定」
  「把原因照实说给用户」是**写给模型的约束**，模型需要它们）。以前这两类读者
  共用同一份字符串 ⇒ 页面上出现过 `**星号**`、`skill 的档位是「严重」`、
  `（cn_etf）`、甚至「把原因照实说给用户，不要硬给结论」这种对用户毫无意义的指令。
  ⇒ 现在在 `app.py` 的 JSON 出口上统一过一遍 `humanize()`，**只影响 HTTP 这一路**。

★为什么放在边界上、而不是去改 `agent/*.py` 里的原文：
  那些原文是**判据的锚点**。`verify_agent.py` 里有几十条注入锚在
  `portfolio.py` / `portfolio_rules.py` / `tools.py` 的具体某一行字面量上，
  改一个字的措辞就能让一条注入静默漂掉（`check_fault_anchors` 会红，但那时
  你已经分不清是判据坏了还是文案坏了）。边界这一层不碰任何源文件 ⇒ 零锚点风险。

★四条硬约束（前三条是踩出来的，第四条是读判据读出来的，都别动）：
  1. **只改值、不加键、不删键。** `verify_agent.py` 有一条判据钉着 `/api/portfolio`
     失败时 summary 的键**恰好**是 `['error','hint','msg','ok']` —— 加一个
     `user_msg` 之类的键就红。所以人话化是**原地换措辞**，不是新增字段。
  2. **保留锚词。** 游戏页坏掉的那一行必须还含「没取到」：`web/src/probe.ts`
     的 `posErrRows` 靠 `/没取到/` 数行数，行情总览页那条判据认的是
     「这一行没取到」。换掉这个词，判据就**空转成绿**。
  3. **机器读的键不翻译。** `market` / `symbol` / `code` / `error` / `kind` /
     `source` 这些键的**值**是程序要比的（`market == 'cn_etf'` 这类），
     翻成人话等于把契约改了。翻译只落在散文键上。
  4. **「没有硬塞」四个字必须活着到页面。** `verify_agent.py` 那条
     「★组合体检：ETF/指数没被塞进任何行业（页面上明说）」判的就是
     `'没有硬塞' in portNotesText`，而那段文本是**从 HTTP 走过来**的。
     第一版把 `（没有硬塞进任何一个行业）` 整个删掉了 ⇒ 那条判据会红，
     而红得像是"页面漏了一句话"，其实是文案层把判据的锚词吃了。

  ⇒ 2 和 4 不靠"我记得别改那几个词"来保证，而是写成 `_ANCHORS` +
    **改完自检**：任何一条规则吃掉了原文里有的锚词，就整串退回原文。
    （宁可少改一句文案，也不许静默弄坏一条判据。）

★`summary.caveat` / `hypothetical_note` 这两个字段是**写给模型的强制清单**，
  它们跟着 HTTP 一起发出去、但前端**一个字都不渲染**（`Portfolio.tsx` 只渲染
  `data.stress.caveat`，那是另一句、本来就是人话）。所以这里只顺手把它们的
  markdown 记号和内部词洗掉，不重写内容 —— 重写等于替一份没人读的文本编新语义。
"""
import re

# 这些键的值是机器读的，原样保留（约束 3）
_PROTECT_KEYS = {'market', 'symbol', 'code', 'error', 'kind', 'source',
                 'interval_kind', 'name', 'id'}

# 判据在**页面上**认的词（约束 2、4）。改完必须还在，否则整串退回原文。
_ANCHORS = ('没取到', '没有硬塞')

# ── 整串 / 前缀替换：那些"纯指令、对人无意义"的 hint ─────────────────────
# ★用**前缀**而不是整串：这些 hint 的尾巴上挂着各种标点与全角引号，
#   整串匹配一旦源文件改一个引号就静默失配（失配的表现是"原文照发"，
#   看起来像这一层没生效，而不是像出错）。前缀失配的概率低得多。
_PREFIX = [
    ('持仓存在用户自己的浏览器里',
     '你的持仓存在你自己的浏览器里（「模拟投资」页买的那些），这个站不保存。'
     '先去「模拟投资」买几笔，再回来做体检。'),
    ('这两项在「我的画像」里',
     '这两项在「我的画像」里（选档位，不用自己填数字）。先去填一下，再回来算。'),
    ('行情源临时挂了，稍后再试',
     '行情源这会儿取不到数据，稍后再试一次。'),
    ('模型不可用，改走知识',
     '模型现在不可用，请稍后再试。这里不会编一个预测数字给你。'),
    ('问用户要一个更明确的代码',
     '请给我一个更明确的代码，例如 600519、510300、sh000300、00700、AAPL、BTC。'),
    ('必须反问用户指的是哪一个',
     '请告诉我你指的是哪一个。'),
    ('没给代码', '请先告诉我要看哪一只标的。'),
    ('把原因照实说给用户，不要硬给结论',
     '稍后再试一次；如果还是取不到行情，先少放几只标的进来。'),
    ('把原因照实说给用户，不要硬给一个概率', '稍后再试一次。'),
    ('词表里没有这个词，别硬走', '词表里还没有这个词。'),
]

# ── 短语替换：按顺序应用（先长后短，避免短的先吃掉长的一部分）──────────
# ★★这里所有规则都按**去掉 markdown 记号之后**的文本写：`**` / `` ` `` / `★`
#   那三条排在最前面，后面的规则不用再管星号。
_PHRASES = [
    # markdown 记号（人读不到"加粗"，只看到一堆星号）
    ('**', ''), ('`', ''), ('★', ''),

    # 内部框架名（`skills/` 那套 md 是本站的分析依据，用户不需要知道它叫 skill）
    ('，skill 的档位是「', '，属于「'),
    ('skill 的档位是「', '属于「'),
    ('，而 skill 的聚集定义要求至少 ', '；判断「几只一起涨跌」至少需要 '),
    ('，skill 的聚集定义要求至少 ', '；判断「几只一起涨跌」至少需要 '),
    ('skill 的聚集定义要求', '判断「几只一起涨跌」需要'),
    ('skill 的偏离线是', '偏离警戒线是'),
    ('skill 的模板里有', '那份分析模板里有'),
    ('skill 的', '分析框架的'),
    ('skill', '分析框架'),

    # ★这一条**必须**留住"没有硬塞"四个字（约束 4）
    ('这几只没有行业（没有硬塞进任何一个行业）：',
     '这几只标的查不到行业分类（没有硬塞一个进去凑数）：'),

    # 取数口径的内部说法
    ('，已从计算中排除（权重按剩下的重新归一化）：', '，没有算进去（占比按剩下的重新折算）：'),
    ('几只标的的交易日不同，按内连接对齐后是 ', '几只标的的交易日不完全一样，只取都有行情的那些日子，一共 '),
    ('—— 没有前向填充，停牌/休市的日子宁可不算。', '—— 停牌、休市那些日子宁可不算，也不拿旧价凑数。'),
    ('，没有公司概况里的行业', '，本来就没有公司行业分类'),
    ('没有 PE/PB/行业这类基本面数据', '没有市盈率、市净率、行业这类基本面数据'),

    # 对用户说话时不用"本站"这种公文腔
    ('本站', '这个站'),

    # 市场内部代号（散文里的；_PROTECT_KEYS 里的值不受影响）
    ('cn_etf', '场内基金'), ('cn_stock', 'A股'), ('cn_index', '指数'),
    ('hk_stock', '港股'), ('us_stock', '美股'), ('crypto', '加密货币'),

    # 反问句里的"用户"是**你**
    ('请先问清用户', '请先告诉我你指的是哪一个'),
]

# ── 正则替换：带数字/带变量的句式 ─────────────────────────────────────
_RES = [
    (re.compile(r'高于 skill 的 ([\d.]+) 门槛'), r'高于 \1 这条集中度警戒线'),
]


# ★`/` 分隔的**机器 token 串**不许被 `_PHRASES` 改写。
#   实测（2026-09-22）：采集器那条 hint 逐字是
#     「scope 用 all / markets / cn / hk / us / crypto / boards / news，可逗号组合」
#   而 `_PHRASES` 里有 `('crypto', '加密货币')` ⇒ 页面上印出来变成
#     「… / 加密货币 / …」 ⇒ 用户**照着页面那句话敲** `加密货币`，而
#     `collector.sources.parse_scope` 回「scope 里有我不认识的词：加密货币」。
#   错得最狠的是失败路径：`api2.ts` 的 `fromBody` 在 `ok:false` 时只取
#   `msg` / `error`+`hint`，而这两处都被改写了 ⇒ **页面唯一那句话把用户
#   引到一个必然再失败的 token 上**。
#   ★判据是"这串是不是**给用户照着敲的**"：一串被 `/` 连起来的、三个以上的
#     小写 token 就是 token 表，不是散文。散文里的 `crypto`（如"crypto 市场
#     24 小时不休"）照旧换成人话 —— 所以这里**不能用"保护整个 hint"那种解法**，
#     那会把 hint 里所有该说人话的地方一起放弃。
_ENUM = re.compile(r'(?<![A-Za-z0-9_])[a-z][a-z_]{1,15}(?:\s*/\s*[a-z][a-z_]{1,15}){2,}')


def human(t):
    """一条字符串 → 人话。非字符串原样返回。"""
    if not isinstance(t, str):
        return t
    s = t
    for head, rep in _PREFIX:                 # 整句是"写给模型的指令" ⇒ 整句换掉
        if s.startswith(head):
            return rep
    keep = []

    def _park(m):                             # 先把 token 串摘出去，改完再放回来
        keep.append(m.group(0))
        return '\x00%d\x00' % (len(keep) - 1)

    out = _ENUM.sub(_park, s)
    for pat, rep in _RES:
        out = pat.sub(rep, out)
    for a, b in _PHRASES:
        out = out.replace(a, b)
    for i, v in enumerate(keep):              # ★原样放回：token 表一个字节都不许动
        out = out.replace('\x00%d\x00' % i, v)
    out = re.sub(r'[ \t]+\n', '\n', out)
    # ★锚词自检（约束 2、4）：任何一条规则把判据在页面上认的词吃掉了，
    #   就整串退回原文 —— 判据空转成绿比文案难看坏得多。
    for a in _ANCHORS:
        if a in s and a not in out:
            return s
    return out


def humanize(obj):
    """递归地把一个 JSON 结构里**散文键**的值换成人话（约束 1、3）。"""
    if isinstance(obj, dict):
        return {k: (v if k in _PROTECT_KEYS else humanize(v)) for k, v in obj.items()}
    if isinstance(obj, list):
        return [humanize(x) for x in obj]
    return human(obj)
