# ══ 判档 ════════════════════════════════════════════════════════════════

def _pick(scale, value):
    """在有序档位表里找 value 落在哪一档。`None` 进 `None` 出（缺数据不判档）。

    ★区间是**含下界、不含上界**的（和 md 里 `5–10%` 的写法一致），
      但 `lo == hi` 那种"单点档"（EDR 的 `~1.0`）按**等于**判 ——
      不然它永远匹配不到，而"约等于 1.0"恰恰是最该被报出来的那一档。
    """
    if value is None:
        return None
    for lo, hi, name in scale:
        if lo is not None and hi is not None and lo == hi:
            if abs(value - lo) < 1e-9:
                return name
            continue
        if (lo is None or value >= lo) and (hi is None or value < hi):
            return name
    return None


def _rank(scale, level):
    """档位在表里的位置（0 = 最轻）。找不到返回 -1。"""
    for i, (_lo, _hi, name) in enumerate(scale):
        if name == level:
            return i
    return -1


def grade(metrics):
    """算好的指标 → 一条条档位。★**只报档位，不合并成总分**（理由见 MD_NOT_COMPUTED）。

    输入 `metrics`（缺的键 = "这项算不了"，**不会猜一个**）：
      weights      每只的权重（百分数，已归一化，和为 100）：[{'symbol','name','weight'}]
      top5         前五大权重之和（百分数）
      hhi          赫芬达尔指数（0–1 的小数）
      edr          有效分散比率
      beta         对基准的 Beta
      clusters     [{'n': 几只, 'avg_corr': 平均两两相关, 'weight': 聚集权重%}]
                   **None = 没算出来**（和 `[]`＝"算了，没发现聚集"是两回事）
      n_holdings   实际参与计算的持仓只数

    返回 `[{'item','level','value','why'}]`，顺序 = 从重到轻。

    ★"从重到轻"用的是**档位在 md 表里的先后**（那张表本身就是从轻写到重的），
      不是我自己发明的一套严重度打分。跨项之间的先后只是**排版**，不是结论 ——
      所以页面上不许出现"最严重的是 X"这种话，只能逐条列。
    """
    out = []

    def add(item, level, value, rank, why):
        out.append({'item': item, 'level': level, 'value': value,
                    'rank': rank, 'why': why})

    # ① 单只集中度：逐只报。
    #    ★'安全'那一档**不报**：一份 20 只持仓的组合会刷出 20 条"安全"，
    #      把真正要看的几条淹掉。它绿着就是绿着，不必占一行。
    for w in (metrics.get('weights') or []):
        lvl = _pick(SINGLE_WEIGHT, w.get('weight'))
        if lvl and lvl != '安全':
            add('单只集中度·%s' % (w.get('name') or w.get('symbol') or '?'),
                lvl, round(w['weight'], 1), _rank(SINGLE_WEIGHT, lvl),
                '单只占 %.1f%%，skill 的档位是「%s」' % (w['weight'], lvl))

    # ② 前五大 + HHI
    top5 = metrics.get('top5')
    lvl = _pick(TOP5, top5)
    if lvl:
        add('前五大集中度', lvl, round(top5, 1), _rank(TOP5, lvl),
            '前五大合计 %.1f%%，skill 的档位是「%s」' % (top5, lvl))
    hhi = metrics.get('hhi')
    if hhi is not None and hhi > HHI_ALERT:
        add('HHI（赫芬达尔指数）', '集中', round(hhi, 3), 2,
            'HHI %.3f 高于 skill 的 %.2f 门槛' % (hhi, HHI_ALERT))

    # ③ 相关性聚集
    #    ★这里最容易出的错是"1 只持仓也报一条"：一只谈不上相关性，两两相关在数学上
    #      不存在。所以先判只数 —— 不够就明说**不够**，而不是把它算成"分散良好"。
    n = metrics.get('n_holdings')
    clusters = metrics.get('clusters')
    if clusters is None:
        if n is not None and n < CLUSTER_MIN_N:
            why = ('只有 %d 只持仓，而 skill 的聚集定义要求**至少 %d 只**平均两两相关'
                   ' > %.2f —— 一只谈不上相关性。这不是"分散良好"，是**没测**。'
                   % (n, CLUSTER_MIN_N, CLUSTER_MIN_CORR))
        else:
            why = ('周收益率相关系数没算出来（历史不够长或取数失败），'
                   '聚集检测做不了 —— 这不是"没发现聚集"。')
        add('相关性聚集', '算不了', n, -1, why)
    else:
        for c in clusters:
            add('相关性聚集（%d 只）' % c['n'], '聚集',
                round(c.get('weight', 0), 1), 2,
                '%d 只持仓的平均两两相关 %.2f 高于 %.2f，合起来占 %.1f%% 权重 —— '
                '名字不同、走势是一条线'
                % (c['n'], c['avg_corr'], CLUSTER_MIN_CORR, c.get('weight', 0)))

    # ④ 有效分散比率
    #    ★和 ③ 同一个坑、同一个修法：**一只持仓时 EDR 恒等于 1** ——
    #      Σσ 就是它自己那一个 σ，而"组合"就是它本身。这不是"分散效果极差"，
    #      是这个数在单只上**根本不是一次测量**。拿一个恒等式去报最坏那一档，
    #      和"不算健康总分"是同一条纪律：不许用编出来的东西稀释真的。
    #      （两只就谈得上了：两只不相关的等波动标的恰好给 1.41。）
    edr = metrics.get('edr')
    if edr is not None and n is not None and n < 2:
        add('有效分散比率（EDR）', '算不了', round(edr, 3), -1,
            '只有 %d 只持仓，EDR 恒为 %.2f（组合就是它自己那一个 σ）——'
            '这不是"几乎无分散"，是**这个数在单只上没含义**。分散至少要两只才谈得上。'
            % (n, edr))
    else:
        lvl = _pick(EDR, edr)
        if lvl:
            # ★这张表是**从坏写到好**的（~1.0 → >1.5），和上面两张反过来，
            #   所以 rank 要倒过来算，否则"几乎无分散"会被排到最后。
            add('有效分散比率（EDR）', lvl, round(edr, 3),
                len(EDR) - 1 - _rank(EDR, lvl),
                'EDR %.3f（各持仓波动率之和 ÷ 组合波动率），skill 的档位是「%s」'
                % (edr, lvl))

    # ⑤ Beta 偏离
    b = metrics.get('beta')
    if b is not None and (b > BETA_HIGH or b < BETA_LOW):
        side = ('偏高（放大市场波动）' if b > BETA_HIGH
                else '偏低（和市场不同步）')
        add('市场因子（Beta）', '偏离', round(b, 3), 1,
            'Beta %.3f %s；skill 的偏离线是 > %.1f 或 < %.1f'
            % (b, side, BETA_HIGH, BETA_LOW))

    # ★排序用 rank（= 档位在 md 表里的位置），并且**稳定**：Python 的 sort 是稳定的，
    #   同 rank 保持插入顺序，所以同一份输入永远给同一个顺序 ——
    #   页面上不会出现"刷新一下顺序变了"。
    out.sort(key=lambda r: -r['rank'])
    for r in out:
        r.pop('rank', None)
    return out
