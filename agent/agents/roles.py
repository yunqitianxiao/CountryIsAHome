# ── 提示词组装（★每轮现拼，不缓存）────────────────────────────────────

def _hist(history):
    """和 `llm.build_messages` **同一口径**的切片：只留 user/assistant 的正文，最多 3 轮。

    ★口径必须一致：两边不一样的话，"提示词里说聊过 X、但 X 其实没进上下文"
      这种不一致迟早出现，而且症状是"模型答非所问"，没人会想到是切片规则不同。
    """
    return [h for h in (history or [])[-6:]
            if isinstance(h, dict) and h.get('role') in ('user', 'assistant')
            and h.get('content')]


def _turn_blocks(history, profile, block):
    """这一轮里**会过期**的那几块。★`profile` 用 `llm.profile_block`，一个字都不重写。

    为什么不自己写一份画像清洗：那是**同一条安全边界**（客户端送来的字符串直通
    系统提示词，换行能伪造段落）。两份清洗就是两条边，其中一条迟早会松
    （`llm.py` 里那三条硬规矩 + 判据都在那边，照抄一份等于把它们复制到没人守的地方）。
    """
    import llm
    parts = []
    pb = llm.profile_block(profile)           # 没填过 ⇒ ''（整段不出现）
    if pb:
        parts.append(pb)
    lc = llm.live_context(history)            # 今天几号 / 本期回测口径 / 聊到哪了
    if lc:
        parts.append(lc)
    parts.append(
        '【会议纪律】你在一个多智能体会议上发言：\n'
        '- 你只代表**你自己这个视角**，别替别的角色说话，也别把别人的活干了。\n'
        '- 有分歧就说分歧在哪（对的是哪一个数、哪一条推理），**不要含糊过去**。\n'
        '- 你说的每句话都会被记录下来、和别人的并排展示，所以要能被复核。')
    if block:
        parts.append(block)
    return parts


