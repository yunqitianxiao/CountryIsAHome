# 团长给全团立的规矩。★每条都对着一种会让"导览"变成"编"的走法。
SHARED = """【导览团纪律】
- 你**只看得到目录里分给你的那一块**，别人那块你看不到。被问到看不到的东西，
  就说"这块不归我，我说不了"，**不许猜、不许按常理补一个**。
- 你这一趟只干自己的活，别替别的导览员答。
- **凡是你说的数字，都必须出现在下面那段目录里**，一个字都不许改（"255 个词条"就写 255）。
  目录里没有的数，一个字都不要写。
- 说人话，2~4 句。用户是**理财新手**，不要术语堆砌。
- 用户是在**问这个站怎么用**，不是在问投资建议。**任何情况下都不给买卖建议**。"""


# 主持提示词里"导览员原话"那一段的抬头。★桩（`__init__._stub_transport`）
# 靠它切出"主持被允许引用的那一段"——两处必须是同一个字符串，所以放成常量。
LINES_MARK = '【导览员们的原话（一个字都没改）】'


def _docent_persona(role):
    return ('你是「乡e家」网站**导览团**里的**%s**（导览员 id：%s）。\n'
            '这个团的工作是：带一个刚打开这个站的人看清**这个站是怎么搭的、东西在哪儿、'
            '哪个数字有实测撑着**。你不做投资建议，也不评价行情。\n\n'
            '【你的活】%s' % (NAMES[role], role, JOBS[role]))


def docent_messages(role, question, history=None, block=None):
    """一个导览员这一趟的 messages。★`block` 只有它自己那一块目录。"""
    if role not in DOCENTS:
        raise ValueError('没有这个导览员：%r' % role)
    sys_parts = [_docent_persona(role), SHARED]
    if block:
        sys_parts.append('【分给你的目录】\n%s' % block)
    else:
        sys_parts.append('【分给你的目录】\n（这一趟没有读到目录 —— 那就**直说读不到**，'
                         '一个字都不要编。）')
    msgs = [{'role': 'system', 'content': '\n\n'.join(sys_parts)}]
    for h in _hist(history):
        msgs.append({'role': h['role'], 'content': str(h['content'])[:4000]})
    msgs.append({'role': 'user', 'content': '【用户的问题】%s' % (question or '').strip()})
    return msgs


def _hist(history):
    """与 `llm.build_messages` 同一口径的切片（只留 user/assistant 正文，最多 3 轮）。"""
    return [h for h in (history or [])[-6:]
            if isinstance(h, dict) and h.get('role') in ('user', 'assistant')
            and h.get('content')]


def host_messages(question, history=None, lines=(), overview=''):
    """主持这一趟的 messages。

    ★ 主持拿到的**只有两样**：站点定位（不含任何计数）+ 各导览员的**原话**。
      它手上一个数都没有 —— 这不是省事，是"数字从哪来"要有唯一答案：
      成稿里每个数都得能指回某个导览员那句原话，然后校对位再去目录里查那句原话。
      把整份目录发给主持（= 把"只答自己那块"这条结构又拆掉），
      那么"主持编的数"和"导览员说的数"在成稿里就分不出来了。

    ★ 导览员的话是**原样给**的（不摘要）：摘要会把"这个数是谁说的"磨掉，
      而那句话正是校对位唯一的锚。
    """
    sys_parts = [
        '你是「乡e家」网站**导览团**的**主持人**（角色 id：host）。\n'
        '这个团带一个刚打开这个站的人看清**这个站是怎么搭的、东西在哪儿、'
        '哪个数字有实测撑着**。\n\n'
        '【你的活】把下面几位导览员说过的话，**组织成一段回答**讲给用户听。\n'
        '- 你**只能转述他们说过的话**：他们说了什么你就说什么，他们没说的你就不说。\n'
        '- 他们之间**没有冲突**（各管一块），所以不要制造分歧、也不要"综合权衡"。\n'
        '- ★**一个数字都不许自己算、自己补、自己约**。要用的数必须原样来自某位导览员，'
        '  而且必须带它原来的口径（"255 个词条"不能写成"两百多个"、"大约 250"）。\n'
        '- 用户问到的、但**没有一位导览员提到**的东西：直说"这个站上没有这块"，'
        '  **不许**按常理补一个（补出来的数看着最专业，也最坏）。\n'
        '- 2~6 句，先给结论。用户是**理财新手**。\n'
        '- **任何情况下都不给买卖建议**，不给涨跌判断。',
        SHARED,
    ]
    if overview:
        sys_parts.append('【这个站是什么（定位，不含任何数字）】\n%s' % overview)
    body = []
    for r in lines:
        t = (r.get('text') or '').strip()
        body.append('- %s（%s）：%s' % (r.get('name'), r.get('role'),
                                        t or '★这一位这一趟没说出话来'))
    if body:
        sys_parts.append(LINES_MARK + '\n' + '\n'.join(body))
    else:
        sys_parts.append(LINES_MARK + '\n（这一趟没有一位导览员说出话来 —— '
                         '那就直说这次没查成，别自己答。）')
    msgs = [{'role': 'system', 'content': '\n\n'.join(sys_parts)}]
    for h in _hist(history):
        msgs.append({'role': h['role'], 'content': str(h['content'])[:4000]})
    msgs.append({'role': 'user', 'content': '【用户的问题】%s' % (question or '').strip()})
    return msgs
