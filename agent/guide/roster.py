#!/usr/bin/env python3
"""导览团的名册与提示词。

★ 这个团和 `agents/`（议会）是**两套东西**，共用只有"多个角色分头干活"这一条：

  · 议会是**对抗**：多空两轮交锋、按表现算权重、风控一票否决。
  · 导览团是**分工**：每人只管目录里的一块，互不反驳、不算权重、没有否决票。
    收口的那个（主持）手上**一个数都没有**，只能转述导览员说过的话；
    再配一个非 LLM 的校对位（`audit.py`）查成稿里的数字出没出处。

  所以这里没有 `stance` / `conf` / `rebuttal` —— 那些是博弈的零件，
  导览团不需要，硬套上去会让"导览"看着像"下注"。
"""

